// Stage 01, step 2: describe the snapshot - tree, file types, sizes, dates, existing diagrams.
import fs from 'node:fs';
import path from 'node:path';
import { P, main, walk, writeText, readYaml, UserError, rel } from './lib/common.mjs';

const DIAGRAM_EXT = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg', '.drawio', '.excalidraw', '.puml', '.mmd']);
const TEXT_EXT = new Set(['.md', '.txt', '.yml', '.yaml', '.json', '.ps1', '.psm1', '.js', '.mjs', '.ts', '.py', '.sh', '.toml', '.ini', '.cfg', '.css', '.html', '.xml', '.csv']);
const kb = (n) => (n < 1024 ? `${n} B` : `${(n / 1024).toFixed(1)} KB`);
const day = (d) => d.toISOString().slice(0, 10);

main(() => {
  const prov = readYaml(path.join(P.sources, 'provenance.yml'));
  if (!prov) throw new UserError('No snapshot. Run scripts/snapshot-sources.mjs first.');
  const lines = ['# Source Inventory', '', 'Generated by `scripts/inventory-sources.mjs`. Paths are relative to `output/sources/`.', ''];
  lines.push('| Source | Role | Kind | Files | Size | Newest change | Commit |', '| --- | --- | --- | --- | --- | --- | --- |');
  const sections = [];
  for (const s of prov.sources) {
    const dir = path.join(P.sources, s.id);
    const files = walk(dir);
    const stats = files.map((f) => ({ f, r: path.relative(P.sources, f).split(path.sep).join('/'), st: fs.statSync(f) }));
    const size = stats.reduce((a, x) => a + x.st.size, 0);
    const newest = stats.reduce((a, x) => (x.st.mtime > a ? x.st.mtime : a), new Date(0));
    lines.push(`| \`${s.id}\` | ${s.role} | ${s.kind} | ${files.length} | ${kb(size)} | ${files.length ? day(newest) : '-'} | ${s.repo_commit ? s.repo_commit.slice(0, 7) + (s.repo_dirty ? ' (dirty)' : '') : '-'} |`);

    const byExt = {};
    for (const x of stats) { const e = path.extname(x.f).toLowerCase() || '(none)'; byExt[e] = (byExt[e] || 0) + 1; }
    const diagrams = [];
    for (const x of stats) {
      const e = path.extname(x.f).toLowerCase();
      if (DIAGRAM_EXT.has(e)) diagrams.push(`\`${x.r}\` (${e.slice(1)})`);
      else if (TEXT_EXT.has(e) && x.st.size < 512 * 1024) {
        const t = fs.readFileSync(x.f, 'utf8');
        const n = (t.match(/```mermaid/g) || []).length;
        if (n) diagrams.push(`\`${x.r}\` (${n} mermaid block${n > 1 ? 's' : ''})`);
      }
    }
    const sec = [`## ${s.id}`, '', `Origin: \`${s.origin}\`. ${s.note || ''}`.trim(), ''];
    sec.push('File types: ' + Object.entries(byExt).sort((a, b) => b[1] - a[1]).map(([e, n]) => `${e} ${n}`).join(', '), '');
    if (s.skipped?.length) sec.push(`Skipped at snapshot: ${s.skipped.map((k) => `\`${k.path}\` (${k.reason})`).join('; ')}`, '');
    sec.push(`Existing diagrams: ${diagrams.length ? diagrams.join('; ') : 'none'}`, '');
    sec.push('```', ...tree(dir, s.id, stats), '```', '');
    sections.push(...sec);
  }
  lines.push('', ...sections);
  writeText(path.join(path.dirname(P.sources), 'inventory.md'), lines.join('\n'));
  console.log(`Wrote ${rel(path.join(path.dirname(P.sources), 'inventory.md'))}`);
});

function tree(dir, name, stats) {
  const out = [`${name}/`];
  const visit = (d, prefix) => {
    const entries = fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.isDirectory() === b.isDirectory() ? a.name.localeCompare(b.name) : a.isDirectory() ? -1 : 1));
    entries.forEach((e, i) => {
      const last = i === entries.length - 1;
      const full = path.join(d, e.name);
      if (e.isDirectory()) { out.push(`${prefix}${last ? '└── ' : '├── '}${e.name}/`); visit(full, prefix + (last ? '    ' : '│   ')); }
      else {
        const st = stats.find((x) => x.f === full)?.st;
        out.push(`${prefix}${last ? '└── ' : '├── '}${e.name}${st ? `  (${kb(st.size)}, ${day(st.mtime)})` : ''}`);
      }
    });
  };
  visit(dir, '');
  return out;
}
